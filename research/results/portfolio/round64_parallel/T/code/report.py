# random benchmark: per replication one random entry per event (from its pool), cell rule applied, VAL only
w("## Random benchmark (VAL; one random entry per event and replication in [T - 7 d, T - 48 h], gap rule recomputed, hold 24 h at market)")
pool = {}
for q in RP:
    if 2022 <= q["year"] <= 2024:
        pool.setdefault((q["perp"], q["side"]), []).append(q)
NREP = 2000
actual = {}
for s, k in cells:
    rs = sel(s, k, era="VAL")
    actual[(s, k)] = (net(rs).mean() if rs else np.nan, cl_t(net(rs), [r["day"] for r in rs]) if rs else np.nan)
perps = sorted({q["perp"] for q in RP if 2022 <= q["year"] <= 2024})
rep_means = {c: [] for c in cells}
rep_max = []
for i in range(NREP):
    mx = -np.inf
    for s, k in cells:
        xs = []
        for p in perps:
            lst = pool.get((p, s))
            if not lst:
                continue
            q = lst[rng.integers(len(lst))]
            ok = q["gap"] > k if s == "T1" else q["gap"] < -k
            if ok:
                xs.append(q["net0"] - COST[s])
        if xs:
            m = float(np.mean(xs)); rep_means[(s, k)].append(m); mx = max(mx, m)
    rep_max.append(mx)
for s, k in cells:
    a = actual[(s, k)][0]
    rm = np.array(rep_means[(s, k)])
    if len(rm) and np.isfinite(a):
        w("- %s k%d: actual %+.1f bp; random mean %+.1f bp, p95 %+.1f; actual beats %.1f%% of random" % (
            s, int(k * 1e4), 1e4 * a, 1e4 * rm.mean(), 1e4 * np.percentile(rm, 95), 100 * (rm < a).mean()))
best = max(cells, key=lambda c: actual[c][0] if np.isfinite(actual[c][0]) else -np.inf)
w("- max-over-cells null: best actual cell %s k%d %+.1f bp; random max-over-cells p95 %+.1f bp, best actual beats %.1f%%" % (
    best[0], int(best[1] * 1e4), 1e4 * actual[best][0], 1e4 * np.percentile(rep_max, 95), 100 * (np.array(rep_max) < actual[best][0]).mean()))
w()

